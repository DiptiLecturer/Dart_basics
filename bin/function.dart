void main() {
  print(add(5,6));
  print(sub(5,6));
  print(multiply(5,6));
  print(div(5,6));
  print(mod(5,6));
}

int add(int a, int b, ) => a + b ;
int sub(int a, int b, ) => a - b ;
int multiply(int a, int b, ) => a * b ;
double div(int a, int b, ) => a / b ;
int mod(int a, int b, ) => a % b ;
